const thousandths = (value: number) => Math.round(value * 1000);

/** A pack food as a saved-food request (canonical units: thousandths, small calories, mg). */
export function foodPackRequest(item: FoodPackItem): FoodRequest {
  return {
    name: item.name,
    serving_quantity_milli: thousandths(item.quantity),
    serving_unit: item.unit,
    nutrients: {
      energy_cal: thousandths(item.kcal),
      protein_mg: thousandths(item.protein),
      carbs_mg: thousandths(item.carbs),
      fat_mg: thousandths(item.fat),
      fiber_mg: item.fiber === undefined ? null : thousandths(item.fiber),
    },
  };
}
